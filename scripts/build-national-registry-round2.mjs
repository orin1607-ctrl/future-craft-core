// Builds supabase/migrations/20261018180000_national_registry_round2_sources_staging.sql from
// scripts/national-registry-extra-sources.json (municipal sources + mapped data.gov.il discoveries).
// Usage: node scripts/build-national-registry-round2.mjs
import fs from "node:fs";

const cfg = JSON.parse(fs.readFileSync("scripts/national-registry-extra-sources.json", "utf8"));
const q = (v) => (v == null ? "NULL" : "'" + String(v).replace(/'/g, "''") + "'");
const DS = (rid) => `https://data.gov.il/api/3/action/datastore_search?resource_id=${rid}`;
const OGL = "data.gov.il – מידע ציבורי פתוח (רישיון שימוש חופשי במידע ממשלתי)";
const TLV = "שכבות GIS ציבוריות של עיריית תל אביב־יפו (IView2), שירות ArcGIS פתוח ללא התחברות";

const out = [`-- Staging ONLY: usfeoerkpcafxxlyuldl. Generated by scripts/build-national-registry-round2.mjs – do not edit by hand.
-- National registry, round 2: municipal sources (Tel Aviv GIS, Beer Sheva), mapped data.gov.il discoveries,
-- duplicates marked as completed with the source that holds the data, exact reasons for the rest,
-- Beer Sheva city fix for records already collected from catalog source 62, OpenStreetMap requeued.
`];

// 1. Beer Sheva licensing (catalog 62) is a Beer Sheva municipality dataset: records created without a city get it now,
//    then the source is read again (idempotent per record) so the 95 local 7-digit phones with the 08 prefix are added.
out.push(`UPDATE public.nr_businesses b SET city = 'באר שבע', city_norm = public.nr_norm_city('באר שבע'), updated_at = now()
 WHERE b.city IS NULL AND b.id IN (SELECT e.business_id FROM public.nr_evidence e WHERE e.source_key = 'cat:62' AND e.match_method = 'created');
UPDATE public.nr_sources SET
  name = 'רישוי עסקים – עיריית באר שבע',
  config = config || jsonb_build_object('first_pass', jsonb_build_object('records_read', records_read, 'businesses_new', businesses_new,
           'businesses_enriched', businesses_enriched, 'businesses_merged', businesses_merged, 'details_added', details_added, 'duration_ms', duration_ms)),
  cursor = 0, records_read = 0, businesses_new = 0, businesses_enriched = 0, businesses_merged = 0, details_added = 0, duration_ms = 0,
  status = 'pending', finished_at = NULL,
  status_reason = 'נקרא שוב אחרי תיקון: המאגר שייך לעיריית באר שבע (עיר) וטלפונים בני 7 ספרות מקבלים קידומת 08'
 WHERE key = 'cat:62';`);

// 2. OpenStreetMap: requeue after switching to Overpass mirrors
out.push(`UPDATE public.nr_sources SET status = 'pending', errors = 0, last_error = NULL, cursor = 0, status_reason = 'הוחלף לשרתי Overpass חלופיים – השרת הראשי חוסם בקשות מאזור השרת (HTTP 406 / timeout)'
 WHERE key = 'cat:27';`);

// 3. new / remapped collectors
for (const c of cfg.collect) {
  const config = c.kind === "arcgis"
    ? { layer_url: c.layer_url, oid: c.oid, mapper: c.mapper, page: c.page }
    : { rid: c.rid, map: c.map, ...(c.ckan_base ? { ckan_base: c.ckan_base } : {}) };
  const url = c.kind === "arcgis" ? c.layer_url : c.ckan_base ? `${c.ckan_base}?resource_id=${c.rid}` : DS(c.rid);
  const terms = c.terms || (c.kind === "arcgis" ? TLV : OGL);
  const catalogId = c.catalog_id || (c.key.startsWith("cat:") ? c.key.slice(4) : null);
  out.push(`INSERT INTO public.nr_sources (key, catalog_id, name, url, provider, kind, terms, status, status_reason, priority, config)
VALUES (${q(c.key)}, ${q(catalogId)}, ${q(c.name)}, ${q(url)}, ${q(c.provider || (c.kind === "arcgis" ? "עיריית תל אביב־יפו" : "data.gov.il"))}, ${q(c.kind)}, ${q(terms)}, 'pending', ${q(c.reason_note || null)}, ${c.priority}, ${q(JSON.stringify(config))}::jsonb)
ON CONFLICT (key) DO UPDATE SET name = EXCLUDED.name, url = EXCLUDED.url, provider = EXCLUDED.provider, kind = EXCLUDED.kind, terms = EXCLUDED.terms,
  priority = EXCLUDED.priority, config = EXCLUDED.config, status_reason = EXCLUDED.status_reason,
  status = CASE WHEN nr_sources.records_read = 0 THEN 'pending' ELSE nr_sources.status END, errors = 0, last_error = NULL;`);
}

// 4. duplicates: completed, pointing at the source that holds the same records
for (const a of cfg.alias) {
  out.push(`UPDATE public.nr_sources SET kind = 'alias', status = 'completed', finished_at = now(), status_reason = ${q(a.reason)},
  config = config || jsonb_build_object('alias_of', ${q(a.of)}) WHERE key = ${q(a.key)};`);
}
// 5. not collectable automatically – exact reason
for (const u of cfg.unsupported) {
  out.push(`UPDATE public.nr_sources SET status = 'unsupported', status_reason = ${q(u.reason)} WHERE key = ${q(u.key)};`);
}
// 6. catalog entries whose data is covered by another collected source – status unchanged, reason says where the data is
for (const c of cfg.covered) {
  out.push(`UPDATE public.nr_sources SET status_reason = ${q(c.reason)} WHERE key = ${q(c.key)};`);
}

fs.writeFileSync("supabase/migrations/20261018180000_national_registry_round2_sources_staging.sql", out.join("\n\n") + "\n");
console.log("ok", cfg.collect.length, "collectors,", cfg.alias.length, "aliases,", cfg.unsupported.length, "unsupported,", cfg.covered.length, "covered");
