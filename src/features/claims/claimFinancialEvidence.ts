/**
 * claimFinancialEvidence.ts
 *
 * מנוע אימות והוכחות חזותיות לדוחות שמאי (STAGING).
 * מספק הוכחות חזותיות אמיתיות (Crops) מתוך מסמכי המקור, השוואה סעיף-אחר-סעיף,
 * בדיקה חשבונאית מלאה ומעקב גרסאות שמאות (הצעת תיקון vs חוות דעת סופית).
 */

export interface EvidenceItem {
  id: string;
  clauseName: string;
  sourceDoc: string;
  page: number;
  reportNumber?: string;
  reportDate?: string;
  invoiceNumber?: string;
  isVerifiedSource?: boolean;
  sourceStatusLabel?: string;
  docAmount: number | null;
  docAmountFormatted: string;
  extractedAmount: number | null;
  extractedAmountFormatted: string;
  calculatedAmount: number | null;
  calculatedAmountFormatted: string;
  diff: number;
  status: 'verified' | 'needs_review' | 'error' | 'missing';
  statusLabel: string;
  originalSnippet: string;
  cropUrl?: string;
  notes?: string;
}

export interface ClaimSurveyVersion {
  versionId: string;
  date: string;
  docType: 'הצעת תיקון ראשונית' | 'חשבונית מוסך' | 'חוות דעת שמאי סופית' | 'שומה נגדית' | 'השלמת שומה';
  fileName: string;
  totalAmount: number;
  isSelected: boolean;
  selectionRationale: string;
  cropUrl?: string;
}

export interface AccountingStep {
  step: string;
  formula: string;
  expected: number;
  actual: number;
  passed: boolean;
}

export interface AccountingIntegrityCheck {
  partsSubtotal: number;
  laborSubtotal: number;
  subtotalBeforeVat: number;
  vatRatePercent: number;
  vatAmount: number;
  directDamageTotal: number;
  diminutionOfValue: number;
  finalReportTotal: number;
  surveyorFee?: number;
  grandTotalWithFee?: number;
  isMathematicallySound: boolean;
  arithmeticSteps: AccountingStep[];
  explanation: string;
}

export interface VerificationCertificateData {
  isCertified: boolean;
  certificateText: string;
  inspectedAt: string;
  inspectorName: string;
  plateNumberChecked: string;
  registeredPlate: string;
  plateMatch: boolean;
  documentRef: string;
  documentsChecked: string[];
  reportNumber?: string;
  reportDate?: string;
  invoiceNumber?: string;
  isSourceVerified?: boolean;
  directDamage: number;
  diminution: number;
  appraisalTotal: number;
  surveyorFee: number;
  grandTotal: number;
  // שדות סיכום מורחבים לתעודת אימות (סעיף 5)
  plateOnCard?: string;
  plateOnDoc?: string;
  plateMatchStatus?: string;
  plateSourceLocation?: string;
  pagesCheckedCount?: number;
  suspiciousPagesCount?: number;
  suspiciousPagesNote?: string;
  crossClaimCheckStatus?: string;
  systemDiff?: number;
}

export interface ClaimFinancialEvidencePackage {
  claimId: string;
  plateNumber: string;
  clientName: string;
  surveyorName: string;
  reportNumber?: string;
  reportDate?: string;
  feeInvoiceNumber?: string;
  isSourceVerified?: boolean;
  overallQuality: 'verified' | 'needs_review' | 'missing_report' | 'error';
  overallQualityLabel: string;
  selectedVersion: string;
  versions: ClaimSurveyVersion[];
  items: EvidenceItem[];
  accounting: AccountingIntegrityCheck;
  summaryNotes: string;
  certificate?: VerificationCertificateData;
  plateSourceLocation?: string;
  pagesCheckedCount?: number;
  suspiciousPagesCount?: number;
  crossClaimCheckStatus?: string;
}

