export type FleetCategoryId =
  | 'vehicles'
  | 'drivers'
  | 'vehicle_tracking'
  | 'driver_tracking'
  | 'reports'
  | 'tasks'
  | 'chat';

export type ActionMode = 'read' | 'navigate' | 'write';

export type FleetAction = {
  id: string;
  labelHe: string;
  category: FleetCategoryId;
  description: string;
  fields: string[];
  roles: Array<'super_admin' | 'fleet_manager'>;
  source: string;
  mode: ActionMode;
  needsConfirm: boolean;
  enabled: boolean;
  unavailableReason?: string;
  phrases: string[];
  primary: boolean;
};

