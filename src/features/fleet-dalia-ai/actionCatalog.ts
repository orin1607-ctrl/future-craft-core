const ROLES: Array<'super_admin' | 'fleet_manager'> = ['super_admin', 'fleet_manager'];

const WRITE_LATER = 'פעולת כתיבה קיימת במסך המקורי. בדליה AI היא כבויה עד אישור נפרד.';

function writeAction(partial: Omit<FleetAction, 'mode' | 'needsConfirm' | 'enabled' | 'unavailableReason' | 'roles' | 'primary'> & { primary?: boolean }): FleetAction {
  return {
    ...partial,
    roles: ROLES,
    mode: 'write',
    needsConfirm: true,
    enabled: false,
    unavailableReason: WRITE_LATER,
    primary: partial.primary ?? false,
  };
}

